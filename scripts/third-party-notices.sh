#!/usr/bin/env bash
# Generates THIRD_PARTY_NOTICES.md from the Go modules linked into the
# spec-gate binaries for linux, darwin and windows (the module root). The sample app's npm packages are dev
# dependencies of the template and are not distributed. Run from the repo root.
#   scripts/third-party-notices.sh            write THIRD_PARTY_NOTICES.md
#   scripts/third-party-notices.sh --check    fail if the file is out of date
set -euo pipefail

out=THIRD_PARTY_NOTICES.md
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

license_file() {
  local f
  for f in "$1"/LICENSE "$1"/LICENSE.txt "$1"/LICENSE.md "$1"/COPYING; do
    [ -f "$f" ] && { echo "$f"; return 0; }
  done
  return 1
}

{
  echo "# Third-party notices"
  echo
  echo "spec-gate is licensed under the Apache License 2.0 (see LICENSE)."
  echo "The binary includes the following third-party software."
  echo "This file is generated by \`scripts/third-party-notices.sh\`; do not edit by hand."
  echo

  # every OS goreleaser builds: some modules are linked on one OS only
  # (e.g. mousetrap, used by cobra on windows)
  echo "## Go modules"
  echo
  while read -r path version dir; do
    f=$(license_file "$dir") || { echo "no license file for $path@$version" >&2; exit 1; }
    echo "### $path $version"
    echo
    echo '```'
    cat "$f"
    echo '```'
    echo
  done < <(for goos in linux darwin windows; do
             GOOS=$goos go list -deps -f '{{if .Module}}{{.Module.Path}} {{.Module.Version}} {{.Module.Dir}}{{end}}' .
           done | grep -v '^github.com/nonchan7720/spec-gate ' | sort -u)
} > "$tmp"

if [ "${1:-}" = "--check" ]; then
  if ! cmp -s "$tmp" "$out"; then
    echo "$out is out of date; run: mise run licenses" >&2
    exit 1
  fi
  echo "$out is up to date"
else
  mv "$tmp" "$out"
  trap - EXIT
  echo "wrote $out"
fi
